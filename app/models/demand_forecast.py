import enum
import uuid
from datetime import date

from sqlalchemy import Numeric, Date, ForeignKey, String
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base
from app.core.db_types import str_enum
from app.models.mixins import TimestampMixin


class ForecastMethod(str, enum.Enum):
    MOVING_AVERAGE = "moving_average"
    WEIGHTED_MOVING_AVERAGE = "weighted_moving_average"
    EXPONENTIAL_SMOOTHING = "exponential_smoothing"
    ML_MODEL = "ml_model"  # e.g. XGBoost / LightGBM / Prophet, once enough data exists


class DemandForecast(Base, TimestampMixin):
    """
    Snapshot of a demand/stock-out prediction for a medicine, generated by
    the AI service (Phase 7). Kept as history rather than overwritten each
    run so forecast accuracy can be evaluated over time.
    """

    __tablename__ = "demand_forecasts"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    medicine_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("medicines.id", ondelete="CASCADE"), nullable=False, index=True
    )
    method: Mapped[ForecastMethod] = mapped_column(
        str_enum(ForecastMethod, "forecast_method"), nullable=False
    )
    forecast_date: Mapped[date] = mapped_column(Date, nullable=False)  # date the forecast was run
    predicted_daily_demand: Mapped[float] = mapped_column(Numeric(10, 2), nullable=False)
    predicted_stockout_date: Mapped[date | None] = mapped_column(Date)
    recommended_reorder_qty: Mapped[int | None] = mapped_column()
    notes: Mapped[str | None] = mapped_column(String(255))

    medicine: Mapped["Medicine"] = relationship()
